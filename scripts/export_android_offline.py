#!/usr/bin/env python3
"""Regenerate public Android rules and package an allowlisted Android Studio project.

Uses Python's standard library only; never loads the database or environment files.
"""
import argparse
import ast
import hashlib
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT / "android-offline"
JAVA = PROJECT / "app/src/main/java/com/viscane/offline"


def recognition_files():
    assets = PROJECT / "app/src/main/assets"
    metadata = assets / "recognition-model.json"
    model = assets / "sugarcane_resnet18.onnx"
    if not metadata.exists() and not model.exists():
        return []
    if not metadata.exists() or not model.exists():
        raise ValueError("Incomplete recognition assets. Run scripts/prepare_android_model.py.")
    manifest = json.loads(metadata.read_text())
    if manifest["model_sha256"] != hashlib.sha256(model.read_bytes()).hexdigest():
        raise ValueError("Recognition model checksum mismatch. Regenerate it before exporting.")
    return [metadata, model]


def read_rules():
    source = ROOT / "core/services.py"
    tree = ast.parse(source.read_text(encoding="utf-8"))
    names = {
        "SRA_BASELINE_LKG_TC", "SRA_BASELINE_TC_HA", "CV_MATURITY_BASELINE_WEIGHTS",
        "FERTILIZER_TIMING_GUIDE", "WEEDING_GUIDE", "PLOWING_GUIDE", "AGRONOMIC_KEYS",
    }
    constants = {}
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id in names:
                    constants[target.id] = ast.literal_eval(node.value)
    if set(constants) != names:
        raise ValueError("Public agronomic constants changed; update the exporter.")
    # The actual farmer route overrides the per-variety default weights.
    views = ROOT / "core/views.py"
    function = next(n for n in ast.parse(views.read_text()).body
                    if isinstance(n, ast.FunctionDef) and n.name == "calculate_results")
    payload = next(n.value for n in function.body if isinstance(n, ast.Assign)
                   and any(isinstance(t, ast.Name) and t.id == "payload" for t in n.targets))
    weights = ast.literal_eval(next(v for k, v in zip(payload.keys, payload.values)
                                   if isinstance(k, ast.Constant) and k.value == "custom_weights"))
    return {
        "schema_version": 1,
        "rules_version": hashlib.sha256(source.read_bytes() + views.read_bytes()).hexdigest(),
        "source": "core.services.predict_variety_metrics + calculate_results custom_weights",
        "image_inference_available": bool(recognition_files()),
        "constants": constants,
        "calculator_weights": weights,
    }


def generate_rules():
    rules = read_rules()
    c = rules["constants"]
    varieties = list(c["SRA_BASELINE_LKG_TC"])

    def java(value):
        if isinstance(value, list):
            return "{" + ", ".join(java(v) for v in value) + "}"
        return json.dumps(value, ensure_ascii=True)

    tables = {
        "LKG": [[c["SRA_BASELINE_LKG_TC"][v][s] for s in (1, 2, 3)] for v in varieties],
        "TONS": [[c["SRA_BASELINE_TC_HA"][v][s] for s in (1, 2, 3)] for v in varieties],
        "MATURITY": [[0.0] + [c["CV_MATURITY_BASELINE_WEIGHTS"][v][m]
                              for m in ("NOT_MATURE", "MATURE", "OVER_MATURE")] for v in varieties],
    }
    lines = ["// Generated by scripts/export_android_offline.py. Do not edit.",
             "package com.viscane.offline;", "public final class OfflineRules {",
             "    private OfflineRules() {}",
             f'    public static final boolean IMAGE_RECOGNITION_AVAILABLE = {str(rules["image_inference_available"]).lower()};',
             f'    public static final String VERSION = {java(rules["rules_version"])};',
             f"    public static final String[] VARIETIES = {java(varieties)};",
             "    public static final double[] WEIGHTS = " + java([
                 rules["calculator_weights"][k] for k in c["AGRONOMIC_KEYS"]]) + ";"]
    for name, values in tables.items():
        lines.append(f"    public static final double[][] {name} = {java(values)};")
    for name, key in (("FERTILIZER", "FERTILIZER_TIMING_GUIDE"),
                      ("WEEDING", "WEEDING_GUIDE"), ("PLOWING", "PLOWING_GUIDE")):
        values = [[c[key][v][s] for s in (1, 2, 3)] for v in varieties]
        lines.append(f"    public static final String[][] {name} = {java(values)};")
    lines.append("}")
    JAVA.mkdir(parents=True, exist_ok=True)
    (JAVA / "OfflineRules.java").write_text("\n".join(lines) + "\n", encoding="utf-8")
    assets = PROJECT / "app/src/main/assets"
    assets.mkdir(parents=True, exist_ok=True)
    (assets / "offline-rules.json").write_text(json.dumps(rules, indent=2) + "\n")
    return rules


def package(output):
    generate_rules()
    # Package source only, never local.properties, caches, keys, APKs, or user data.
    files = [PROJECT / name for name in (
        "README.md", "settings.gradle", "build.gradle", "gradle.properties", ".gitignore",
        "app/build.gradle", "app/src/main/AndroidManifest.xml")]
    files.extend(JAVA / name for name in (
        "MainActivity.java", "AssessmentStore.java", "OfflineCalculator.java", "OfflineRules.java",
        "OfflineImageClassifier.java", "ImagePreprocessor.java"))
    files.append(PROJECT / "app/src/main/assets/offline-rules.json")
    files.extend(recognition_files())
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in files:
            archive.write(path, "viscane-offline/" + path.relative_to(PROJECT).as_posix())
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path,
                        default=ROOT / "artifacts/android/viscane-offline.zip")
    args = parser.parse_args()
    print(package(args.output))


if __name__ == "__main__":
    main()
